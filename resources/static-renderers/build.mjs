import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { compile } from 'tailwindcss';

// These renderers cannot load the Vite application, including its runtime or fonts.
const root = new URL('../../', import.meta.url);
const text = (file) => readFile(new URL(file, root), 'utf8');
const theme = await readFile(fileURLToPath(import.meta.resolve('tailwindcss/theme.css')), 'utf8');
const preflight = await readFile(fileURLToPath(import.meta.resolve('tailwindcss/preflight.css')), 'utf8');
const tokens = await text('resources/static-renderers/theme.css');

async function sheet(files, reset = true) {
    const candidates = new Set();
    for (const file of files) {
        for (const attribute of (await text(file)).matchAll(/\bclass="([^"]+)"/g)) {
            for (const name of attribute[1].split(/\s+/)) candidates.add(name);
        }
    }
    const compiler = await compile(`${theme}\n${tokens}\n${reset ? preflight : ''}\n@tailwind utilities;`);
    return compiler.build([...candidates].sort());
}

async function emit(file, content) {
    if (process.argv.includes('--check')) {
        if (await text(file) !== content) throw new Error(`Stale static output: ${file}`);
    } else {
        await writeFile(new URL(file, root), content);
    }
}

await emit('public/scorm-desk.css', await sheet(['layout', 'launch', 'index'].map(
    (page) => `resources/views/scorm-runtime/${page}.blade.php`,
)));
await emit('resources/scorm-static/reader.css', await sheet(['exercise', 'player'].map(
    (page) => `resources/scorm-static/${page}.html`,
)));
await emit('resources/static-renderers/document.css', await sheet([
    'resources/views/assessment/result-sheet.blade.php', 'resources/views/insights/pdf.blade.php',
], false));

const offline = 'resources/static-renderers/offline.html';
const fallback = (await text(offline)).replace('<!-- Offline stylesheet -->', `<style>${await sheet([offline], false)}</style>`);
const worker = await text('resources/static-renderers/worker.js');
await emit('public/portal-worker.js', `// Generated by resources/static-renderers/build.mjs\n${worker.replace('OFFLINE_DOCUMENT', () => JSON.stringify(fallback))}`);
