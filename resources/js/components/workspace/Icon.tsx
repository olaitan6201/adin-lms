export type IconName = keyof typeof components;

function isIconName(name: string): name is IconName {
    return Object.hasOwn(components, name);
}

export function Icon({ name, ...props }: icons.IconProps & { name: string }) {
    const Component = isIconName(name) ? components[name] : icons.InfoIcon;

    return <Component {...props} />;
}
